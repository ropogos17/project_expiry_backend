-- ============================================================
-- 000002_auth_upgrade.up.sql
-- Extend the existing email/password auth model with external
-- identities and hashed refresh-token storage.
-- ============================================================

-- ----------------------------------------
-- Users: allow passwordless / external auth accounts
-- ----------------------------------------

-- PostgreSQL UNIQUE constraints allow multiple NULL values by default,
-- so users without an email can coexist while non-NULL emails stay unique.
ALTER TABLE users
    ALTER COLUMN email DROP NOT NULL;

ALTER TABLE users
    RENAME COLUMN password TO password_hash;

ALTER TABLE users
    ALTER COLUMN password_hash DROP NOT NULL;

-- A local email/password credential still needs an email login identifier.
ALTER TABLE users
    ADD CONSTRAINT chk_users_password_requires_email
    CHECK (password_hash IS NULL OR email IS NOT NULL);

-- ----------------------------------------
-- External authentication identities
-- ----------------------------------------

CREATE TABLE auth_identities
(
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           INTEGER     NOT NULL REFERENCES users (id),
    provider          VARCHAR(50) NOT NULL,
    issuer            TEXT        NOT NULL,
    provider_user_id  TEXT        NOT NULL,
    provider_email    VARCHAR,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_auth_identities_provider_subject
        UNIQUE (provider, issuer, provider_user_id),
    CONSTRAINT chk_auth_identities_provider_not_empty
        CHECK (BTRIM(provider) <> ''),
    CONSTRAINT chk_auth_identities_issuer_not_empty
        CHECK (BTRIM(issuer) <> ''),
    CONSTRAINT chk_auth_identities_provider_user_id_not_empty
        CHECK (BTRIM(provider_user_id) <> '')
);

CREATE INDEX idx_auth_identities_user_id
    ON auth_identities (user_id);

-- ----------------------------------------
-- Refresh tokens: store only the SHA-256 hex digest
-- ----------------------------------------

-- Existing refresh-token rows cannot be safely converted because this
-- schema does not contain the original raw token. Revoke them so every
-- active session is re-authenticated after deployment.
DELETE FROM refresh_tokens;

ALTER TABLE refresh_tokens
    ADD COLUMN token_hash VARCHAR(64) NOT NULL;

ALTER TABLE refresh_tokens
    ADD CONSTRAINT uq_refresh_tokens_token_hash
        UNIQUE (token_hash),
    ADD CONSTRAINT chk_refresh_tokens_token_hash_format
        CHECK (token_hash ~ '^[0-9a-f]{64}$');
