-- ----------------------------------------
-- Lookup / reference tables (no FK deps)
-- ----------------------------------------

CREATE TABLE roles
(
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR NOT NULL UNIQUE
);

CREATE TABLE action_types
(
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR NOT NULL UNIQUE
);

CREATE TABLE categories
(
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR NOT NULL UNIQUE
);

-- ----------------------------------------
-- Users
-- ----------------------------------------

CREATE TABLE users
(
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR     NOT NULL,
    username            VARCHAR     NOT NULL UNIQUE,
    email               VARCHAR     NOT NULL UNIQUE,
    phone               VARCHAR,
    has_avatar          BOOLEAN     NOT NULL DEFAULT FALSE,
    password            VARCHAR     NOT NULL,
    email_verified      BOOLEAN     NOT NULL DEFAULT FALSE,
    phone_verified      BOOLEAN     NOT NULL DEFAULT FALSE,
    two_factor_enabled  BOOLEAN     NOT NULL DEFAULT FALSE,
    two_factor_secret   VARCHAR,
    last_login          TIMESTAMPTZ,
    login_attempts      INTEGER     NOT NULL DEFAULT 0,
    locked_until        TIMESTAMPTZ,
    password_changed_at TIMESTAMPTZ,
    role_id             INTEGER     NOT NULL REFERENCES roles (id),
    is_superuser        BOOLEAN     NOT NULL DEFAULT FALSE,
    deleted_at          TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ----------------------------------------
-- Refresh tokens
-- ----------------------------------------

CREATE TABLE refresh_tokens
(
    id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id    INTEGER     NOT NULL REFERENCES users (id),
    issued_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMPTZ NOT NULL,
    deleted_at TIMESTAMPTZ
);

-- ----------------------------------------
-- Storages
-- ----------------------------------------

CREATE TABLE storages
(
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR NOT NULL,
    description TEXT,
    location    VARCHAR,
    shelf_count INTEGER NOT NULL DEFAULT 1 CHECK (shelf_count >= 1),
    has_image   BOOLEAN NOT NULL DEFAULT FALSE,
    owner       INTEGER NOT NULL REFERENCES users (id),
    deleted_at  TIMESTAMPTZ,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ----------------------------------------
-- Items
-- ----------------------------------------

CREATE TABLE items
(
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR     NOT NULL,
    category_id      INTEGER     NOT NULL REFERENCES categories (id),
    description      TEXT,
    quantity         TEXT,
    has_image        BOOLEAN     NOT NULL DEFAULT FALSE,
    stored_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at       TIMESTAMPTZ NOT NULL,
    storage_id       INTEGER     NOT NULL REFERENCES storages (id),
    shelf            INTEGER     NOT NULL DEFAULT 1 CHECK (shelf >= 1),
    last_modified_by INTEGER     NOT NULL REFERENCES users (id),
    deleted_at       TIMESTAMPTZ
);

-- ----------------------------------------
-- Shares
-- ----------------------------------------

CREATE TABLE shares
(
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_user_id INTEGER     NOT NULL REFERENCES users (id),
    storage_id     INTEGER     NOT NULL REFERENCES storages (id),
    target_user_id INTEGER     NOT NULL REFERENCES users (id),
    can_share      BOOLEAN     NOT NULL DEFAULT FALSE,
    shared_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    UNIQUE (storage_id, target_user_id),
    CHECK (source_user_id <> target_user_id)
);

-- ----------------------------------------
-- Announcements
-- ----------------------------------------

CREATE TABLE announcements
(
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR     NOT NULL,
    description   TEXT,
    external_link TEXT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by    INTEGER     NOT NULL REFERENCES users (id),
    deleted_at    TIMESTAMPTZ
);

-- ----------------------------------------
-- Logs
-- ----------------------------------------

CREATE TABLE logs
(
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    action_type_id INTEGER     NOT NULL REFERENCES action_types (id),
    message        TEXT,
    data           JSONB,
    user_id        INTEGER     NOT NULL REFERENCES users (id)
);

-- ----------------------------------------
-- Indexes
-- ----------------------------------------

-- Users
CREATE INDEX idx_users_role_id ON users (role_id);
CREATE INDEX idx_users_deleted_at ON users (deleted_at);

-- Refresh tokens
CREATE INDEX idx_refresh_tokens_user_id ON refresh_tokens (user_id);
CREATE INDEX idx_refresh_tokens_expires_at ON refresh_tokens (expires_at);

-- Storages
CREATE INDEX idx_storages_owner ON storages (owner);
CREATE INDEX idx_storages_deleted_at ON storages (deleted_at);

-- Items
CREATE INDEX idx_items_storage_id ON items (storage_id);
CREATE INDEX idx_items_category_id ON items (category_id);
CREATE INDEX idx_items_expires_at ON items (expires_at);
CREATE INDEX idx_items_is_deleted_at ON items (deleted_at);

-- Shares
CREATE INDEX idx_shares_source_user_id ON shares (source_user_id);
CREATE INDEX idx_shares_target_user_id ON shares (target_user_id);
CREATE INDEX idx_shares_storage_id ON shares (storage_id);

-- Announcements
CREATE INDEX idx_announcements_created_by ON announcements (created_by);
CREATE INDEX idx_announcements_deleted_at ON announcements (deleted_at);

-- Logs
CREATE INDEX idx_logs_user_id ON logs (user_id);
CREATE INDEX idx_logs_action_type_id ON logs (action_type_id);
CREATE INDEX idx_logs_created_at ON logs (created_at);